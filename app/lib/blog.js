export function getAllBlogPosts() {
  return [...blogPosts].sort(
    (a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()
  )
}

export function getBlogPost(slug) {
  return blogPosts.find((post) => post.slug === slug)
}

export function getRelatedBlogPosts(slug, limit = 3) {
  const post = getBlogPost(slug)
  if (!post) return []

  return getAllBlogPosts()
    .filter((candidate) => candidate.slug !== slug)
    .sort((a, b) => {
      const aKeywordMatches = a.keywords.filter((keyword) =>
        post.keywords.includes(keyword)
      ).length
      const bKeywordMatches = b.keywords.filter((keyword) =>
        post.keywords.includes(keyword)
      ).length

      const aCategoryMatch = a.category === post.category ? 2 : 0
      const bCategoryMatch = b.category === post.category ? 2 : 0

      return bKeywordMatches + bCategoryMatch - (aKeywordMatches + aCategoryMatch)
    })
    .slice(0, limit)
}

export function getBlogPostUrl(slug) {
  return absoluteUrl(`/blog/${slug}`)
}

export function getBlogPostSchema(post) {
  return {
    '@context': 'https://schema.org',
    '@type': 'BlogPosting',
    '@id': `${getBlogPostUrl(post.slug)}#blog-posting`,
    headline: post.title,
    description: post.description,
    datePublished: post.publishedAt,
    dateModified: post.updatedAt,
    author: {
      '@type': 'Organization',
      name: post.author.name,
      url: SITE.baseUrl,
    },
    publisher: {
      '@type': 'Organization',
      name: SITE.name,
      logo: {
        '@type': 'ImageObject',
        url: absoluteUrl('/icon.svg'),
      },
    },
    mainEntityOfPage: getBlogPostUrl(post.slug),
    url: getBlogPostUrl(post.slug),
    inLanguage: 'en-IN',
    keywords: post.keywords.join(', '),
    articleSection: post.category,
    isAccessibleForFree: true,
    isPartOf: {
      '@type': 'Blog',
      name: `${SITE.name} Blog`,
      url: absoluteUrl('/blog'),
    },
  }
}

export function getBlogFaqSchema(post) {
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: post.faq.map((item) => ({
      '@type': 'Question',
      name: item.question,
      acceptedAnswer: {
        '@type': 'Answer',
        text: item.answer,
      },
    })),
  }
}